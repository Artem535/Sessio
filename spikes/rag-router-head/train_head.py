# -*- coding: utf-8 -*-
"""Train the router v2 head: multinomial logistic regression on top of the
same embeddinggemma-2-270m vectors used for retrieval (handoff 17.11 §2).

Input: router_vecs.bin (84x768, LiteRT runtime, plain utterance text — no
recipe prefix) + test/resources/rag/router_ds.tsv labels.
Output: src/rag/router_head_data.h (weights/bias) + REPORT.md metrics.

Caveat: the draft dataset is synthetic and small; leave-one-out accuracy is
the honest estimate here. Retrain on real transcripts before production.
"""
import os
import struct

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CLASSES = ["question", "continuation", "navigation", "ignore"]


def read_matrix(path):
    with open(path, "rb") as f:
        n, dim = struct.unpack("<II", f.read(8))
        return np.frombuffer(f.read(), dtype=np.float32).reshape(n, dim).astype(np.float64).copy()


def train(x, y, iters=3000, lr=0.5, l2=1e-3):
    w = np.zeros((x.shape[1], len(CLASSES)))
    b = np.zeros(len(CLASSES))
    for _ in range(iters):
        logits = x @ w + b
        logits -= logits.max(axis=1, keepdims=True)
        p = np.exp(logits)
        p /= p.sum(axis=1, keepdims=True)
        target = np.eye(len(CLASSES))[y]
        grad = p - target
        w -= lr * (x.T @ grad / len(x) + l2 * w)
        b -= lr * grad.mean(axis=0)
    return w, b


def accuracy(x, y, w, b):
    return float((np.argmax(x @ w + b, axis=1) == y).mean())


def main():
    x = read_matrix(os.path.expanduser("~/.cache/sessio-rag/router_vecs.bin"))
    rows = [l.rstrip("\n").split("\t") for l in open(ROOT + "/test/resources/rag/router_ds.tsv")]
    y = np.array([CLASSES.index(label) for label, _ in rows])
    assert len(y) == len(x)

    w, b = train(x, y)
    train_acc = accuracy(x, y, w, b)
    loo_correct = 0
    for i in range(len(x)):
        mask = np.arange(len(x)) != i
        wi, bi = train(x[mask], y[mask], iters=1500)
        loo_correct += int(np.argmax(x[i] @ wi + bi) == y[i])
    loo_acc = loo_correct / len(x)
    pred = np.argmax(x @ w + b, axis=1)
    binary_true = y != CLASSES.index("ignore")
    binary_pred = pred != CLASSES.index("ignore")
    tp = int((binary_true & binary_pred).sum())
    fp = int((~binary_true & binary_pred).sum())
    fn = int((binary_true & ~binary_pred).sum())
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0

    header = ["#pragma once", "", "// Generated by spikes/rag-router-head/train_head.py — do not edit.",
              "// Router v2 head: multinomial logistic regression on embeddinggemma-2-270m",
              "// vectors of plain utterance text. Classes: question, continuation,",
              "// navigation, ignore. Search-worthy = everything except ignore.", ""]
    header.append("namespace sessio::rag::router_head {")
    header.append("inline constexpr int kClasses = 4;")
    header.append("inline constexpr int kDim = 768;")
    header.append("inline constexpr float kWeights[kClasses][kDim] = {")
    for c in range(len(CLASSES)):
        header.append("    {" + ", ".join(f"{v:.6f}f" for v in w[:, c]) + "},")
    header.append("};")
    header.append("inline constexpr float kBias[kClasses] = {" + ", ".join(f"{v:.6f}f" for v in b) + "};")
    header.append("} // namespace sessio::rag::router_head")
    with open(ROOT + "/src/rag/router_head_data.h", "w") as f:
        f.write("\n".join(header) + "\n")

    report = f"""# Router v2 head — training report

Дата: {__import__('time').strftime('%Y-%m-%d')}. Энкодер: embeddinggemma-2-270m (LiteRT int8, CPU),
plain-текст реплики без recipe-префикса. Данные: router_ds_draft (84 синтетические
реплики, анонимизированная копия в test/resources/rag/router_ds.tsv).
Модель: multinomial logistic regression (4 класса), full-batch GD 3000 итераций,
lr 0.5, L2 1e-3. Веса: src/rag/router_head_data.h.

| Метрика | Значение |
|---|---|
| train accuracy (4 класса) | {train_acc:.3f} |
| leave-one-out accuracy | {loo_acc:.3f} |
| binary search precision | {precision:.3f} |
| binary search recall | {recall:.3f} |

Оговорка: датасет синтетический и маленький, автор правил = автор датасета;
LOO — честная оценка на этих данных. Переобучить на реальных транскриптах
до продакшена (handoff 17.11 §2). Голова включается настройкой, дефолт — правила.
"""
    with open(HERE + "/REPORT.md", "w") as f:
        f.write(report)
    print(report)


if __name__ == "__main__":
    main()
